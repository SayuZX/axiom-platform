import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {createLogs} from './logs.mjs';
const db=new DatabaseSync(':memory:');
db.exec(`CREATE TABLE events(id INTEGER PRIMARY KEY,event_key TEXT,at TEXT,kind TEXT,player_id INTEGER,player_name TEXT,rule TEXT,severity TEXT,details TEXT,reviewed INTEGER);CREATE TABLE audit(id INTEGER PRIMARY KEY,at TEXT,action TEXT,details TEXT);`);
const clock='2026-10-04T12:00:00.000Z',fail=(status,message)=>{throw Object.assign(new Error(message),{status});};
const logs=createLogs({db,fail,text:(s,max)=>{if(typeof s!=='string'||s.length>max||s.includes('\0'))fail(400,'Invalid text');return s;},now:()=>clock,audit:(action,details)=>db.prepare('INSERT INTO audit(at,action,details) VALUES(?,?,?)').run(clock,action,JSON.stringify(details))});
const owner={id:'owner',role:'owner'},other={id:'other',role:'admin'},viewer={id:'viewer',role:'viewer'};
const request=(path,params={},body,user=owner)=>{const url=new URL('http://local/api/logs/'+path);url.search=new URLSearchParams(params);return logs.routes(url.pathname,body===undefined?'GET':'POST',body,url,user);};
const insert=db.prepare('INSERT INTO events VALUES(?,?,?,?,?,?,?,?,?,?)');
for(let id=1;id<=27;id++)insert.run(id,'event-'+id,clock,'detection',id,id===1?'=SUM(1,2)':'Player '+id,id===1?'a,"b"':'damage','high',JSON.stringify({damage:id,identifiers:['license:abc'],note:'quoted "value"\nline'}),0);
insert.run(28,'boundary','2026-10-04T11:00:00.000Z','connection',28,'Boundary','join','info','{}',0);
insert.run(29,'outside','2026-10-04T10:59:59.999Z','connection',29,'Outside','join','info','{}',0);
insert.run(30,'future','2026-10-04T12:00:00.001Z','connection',30,'Future','join','info','{}',0);
assert.equal((await request('events',{preset:'1h'})).total,28);
assert.equal((await request('events',{preset:'all'})).total,30);
const first=await request('events',{preset:'1h',page:'1'}),second=await request('events',{preset:'1h',page:'2'});
assert.deepEqual(first.rows.map(r=>r.id),Array.from({length:25},(_,i)=>27-i));
assert.deepEqual(second.rows.map(r=>r.id),[2,1,28]);
assert.equal((await request('events',{preset:'all',q:"' OR 1=1 --"})).total,0);
assert.equal((await request('events',{preset:'all',filter:'kind=detection AND details.damage=7 AND license=license:abc'})).rows[0].id,7);
assert.equal((await request('events',{preset:'all',filter:'player="Player 9"'})).rows[0].id,9);
assert.equal((await request('events',{preset:'all',filter:'rule="a,\\"b\\""'})).rows[0].id,1);
for(const params of [{page:'0'},{page:'1.5'},{limit:'26'},{sort:'at; DROP TABLE events'},{filter:'kind=detection OR rule=damage'},{filter:'details.x[0]=1'},{filter:'rule=x AND'},{preset:'custom',from:'2026-02-30T00:00:00Z',to:clock},{preset:'custom',from:clock,to:'2026-10-03T00:00:00Z'},{preset:'custom',from:'yesterday',to:clock}])await assert.rejects(request('events',params),e=>e.status===400);
const bounds={preset:'custom',from:'2026-10-04T13:00:00+02:00',to:'2026-10-04T14:00:00+02:00'};
assert.equal((await request('events',bounds)).total,28);
const stats=await request('stats',{preset:'1h'});
assert.deepEqual(stats.byKind.map(r=>({...r})),[{label:'detection',count:27},{label:'connection',count:1}]);
assert.equal(stats.timeline.reduce((n,r)=>n+r.count,0),28);
const exported=await request('export',{preset:'all',filter:'player=1',format:'csv'});
assert.ok(exported.content.includes('"\'=SUM(1,2)"'));
assert.ok(exported.content.includes('"a,""b"""'));
assert.equal(JSON.parse((await request('export',{preset:'1h'})).content).length,28);
const bookmark=await request('bookmarks',{}, {name:'My evidence',filters:{preset:'1h',filter:'kind=detection'}});
assert.equal((await request('bookmarks')).bookmarks[0].name,'My evidence');
assert.deepEqual((await request('bookmarks',{},undefined,other)).bookmarks,[]);
await assert.rejects(request(`bookmarks/${bookmark.id}/delete`,{}, {},other),e=>e.status===404);
await assert.rejects(request('bookmarks',{}, {name:'Read only',filters:{}},viewer),e=>e.status===403);
assert.equal((await request('audit',{preset:'1h',action:'logs.bookmark.save',q:'owner'})).total,1);
assert.equal((await request('audit',{preset:'1h',action:'logs.bookmark.delete'})).total,0);
await request(`bookmarks/${bookmark.id}/delete`,{},{});
assert.deepEqual((await request('bookmarks')).bookmarks,[]);
assert.equal((await request('audit',{preset:'1h',action:'logs.bookmark.delete'})).total,1);
db.close();
console.log('Logs boundary, filtering, export, paging, statistics and bookmark isolation checks passed.');
