// Run: bun tests/axiom-history.check.ts
import { strict as assert } from 'node:assert';
import { getAxiomHistory, initializeAxiomHistory, setHistoryTitles, setHistoryContent, flushAxiomHistory } from '../src/lib/axiomHistory';
const requests: { expectedVersion: number; titles: string[]; content: Record<string, { role: string; text: string }[]> }[] = [];
let conflict = false;
// Minimal browser host for the notification boundary in this non-DOM check.
const browserEvents = new EventTarget();
globalThis.window = { parent: { postMessage() {} }, location: { origin: 'https://example.test' }, addEventListener: browserEvents.addEventListener.bind(browserEvents) } as unknown as Window & typeof globalThis;
globalThis.location = window.location;
Object.defineProperty(globalThis, 'localStorage', { value: { getItem() { throw new Error('History must never read legacy local storage'); } }, configurable: true });
globalThis.fetch = (async (_url: unknown, options?: RequestInit) => {
  assert.equal(options?.redirect, 'error');
  if (!options?.method) return Response.json({ version: 3, titles: [], content: {} });
  const body = JSON.parse(options.body as string); requests.push(body);
  return conflict ? Response.json({}, { status: 409 }) : Response.json({ version: body.expectedVersion + 1 });
}) as typeof fetch;
await initializeAxiomHistory();
setHistoryTitles(['owned']);
const unsavedNavigation = new Event('beforeunload', { cancelable: true });
browserEvents.dispatchEvent(unsavedNavigation);
assert.equal(unsavedNavigation.defaultPrevented, true);
setHistoryContent({ owned: [{ role: 'user', text: 'hello' }] });
await flushAxiomHistory();
assert.equal(requests.length, 1);
assert.equal(requests[0].expectedVersion, 3);
assert.equal(requests[0].content.owned[0].text, 'hello');
let release: (() => void) | undefined;
let started: (() => void) | undefined;
const sending = new Promise<void>(resolve => { started = resolve; });
const gate = new Promise<void>(resolve => { release = resolve; });
const fetchNow = globalThis.fetch;
globalThis.fetch = (async (url: unknown, options?: RequestInit) => { started?.(); await gate; return fetchNow(String(url), options); }) as typeof fetch;
setHistoryContent({ owned: [{ role: 'user', text: 'first snapshot' }] });
await sending;
setHistoryContent({ owned: [{ role: 'user', text: 'latest snapshot' }] });
release?.();
await flushAxiomHistory();
assert.equal(requests[1].expectedVersion, 4);
assert.equal(requests[2].expectedVersion, 5);
assert.equal(requests[1].content.owned[0].text, 'first snapshot');
assert.equal(requests[2].content.owned[0].text, 'latest snapshot');
globalThis.fetch = fetchNow;
conflict = true;
setHistoryTitles(['renamed']);
await assert.rejects(flushAxiomHistory(), /not saved/i);
assert.match(getAxiomHistory().error, /not saved/i);
const count = requests.length;
setHistoryTitles([]);
await assert.rejects(flushAxiomHistory(), /not saved/i);
assert.equal(requests.length, count, 'conflict must halt writes');
assert.equal(getAxiomHistory().version, 6);
const conflictNavigation = new Event('beforeunload', { cancelable: true });
browserEvents.dispatchEvent(conflictNavigation);
assert.equal(conflictNavigation.defaultPrevented, true);
console.log('History CAS checks passed');
