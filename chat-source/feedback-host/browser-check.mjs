// Run after build: CHROME_PATH='/path/to/Chrome' node browser-check.mjs
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(`${process.env.AXIOM_SDK_REPO || '/tmp/supergpt-source'}/package.json`);
const { chromium } = require('playwright-core');
const server = createServer(async (req, res) => {
  if (req.url === '/axiom-feedback.js') { res.setHeader('Content-Type', 'text/javascript'); res.end(await readFile(new URL('./dist/axiom-feedback.js', import.meta.url))); return; }
  res.setHeader('Content-Type', 'text/html');
  if (req.url.startsWith('/axiom-chat/') || req.url === '/untrusted.html') { res.end('<!doctype html><button id="child">Frame action</button>'); return; }
  res.end('<!doctype html><style>body{margin:23px}button{border-radius:0}#card{width:333px;height:111px;background:red}</style><button id="trigger">Trigger</button><div id="card">Unchanged host</div><iframe id="trusted" src="/axiom-chat/index.html"></iframe><iframe id="untrusted" src="/untrusted.html"></iframe><script type="module" src="/axiom-feedback.js"></script>');
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH, channel: process.env.CHROME_PATH ? undefined : 'chrome', headless: true });
try {
  const page = await browser.newPage();
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.waitForFunction(() => !!window.axiomNotify);
  const baseline = await page.locator('#card').boundingBox();
  await page.evaluate(() => { window.axiomNotify({kind:'success',message:'Saved'}); window.axiomNotify({kind:'error',message:'Failed'}); });
  await page.getByRole('status').filter({hasText:'Saved'}).waitFor();
  await page.getByRole('alert').filter({hasText:'Failed'}).waitFor();
  assert.deepEqual(await page.locator('#card').boundingBox(), baseline);
  assert.equal(await page.locator('.axiom-notice').count(), 0);
  assert.equal(await page.locator('[data-color="success"].d-sdk-alert').count(), 1);
  assert.equal(await page.locator('[data-color="danger"].d-sdk-alert').count(), 1);
  const light = await page.evaluate(() => { const root = window.axiomFeedbackHost().shadowRoot; const toast = root.querySelector('.d-sdk-toast'); return { background: getComputedStyle(toast).backgroundColor, width: toast.getBoundingClientRect().width, theme: root.querySelector('.axiom-root').dataset.theme }; });
  assert.equal(light.theme, 'light');
  assert.ok(light.width <= 340);
  await page.evaluate(() => { document.documentElement.classList.add('dark'); window.dispatchEvent(new Event('axiom-theme-change')); });
  const dark = await page.evaluate(() => { const root = window.axiomFeedbackHost().shadowRoot; return { background: getComputedStyle(root.querySelector('.d-sdk-toast')).backgroundColor, theme: root.querySelector('.axiom-root').dataset.theme }; });
  assert.equal(dark.theme, 'dark');
  assert.notEqual(dark.background, light.background);
  await page.evaluate(() => document.documentElement.classList.remove('dark'));
  await page.locator('#trigger').focus();
  await page.evaluate(() => { window.results = []; window.axiomConfirm({message:'First'}).then(v => window.results.push(v)); window.axiomConfirm({message:'Second'}).then(v => window.results.push(v)); });
  await page.getByRole('dialog').filter({hasText:'First'}).waitFor();
  assert.ok((await page.getByRole('dialog').boundingBox()).width <= 380);
  assert.equal(await page.getByRole('button',{name:'Batal',exact:true}).evaluate(el => el.getRootNode().activeElement === el), true);
  await page.keyboard.press('Shift+Tab');
  assert.equal(await page.getByRole('button',{name:'Lanjutkan',exact:true}).evaluate(el => el.getRootNode().activeElement === el), true);
  await page.keyboard.press('Tab');
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').filter({hasText:'Second'}).waitFor();
  await page.getByRole('button',{name:'Lanjutkan',exact:true}).click();
  await page.waitForFunction(() => window.results.length === 2);
  assert.deepEqual(await page.evaluate(() => window.results), [false,true]);
  assert.equal(await page.evaluate(() => document.activeElement.id), 'trigger');
  const frame = page.frames().find(f => f.url().endsWith('/axiom-chat/index.html'));
  await frame.evaluate(() => parent.postMessage({type:'axiom-notify',kind:'success',message:'Frame saved'}, location.origin));
  await page.getByRole('status').filter({hasText:'Frame saved'}).waitFor();
  await frame.evaluate(() => { window.addEventListener('message', e => { if(e.data.type === 'axiom-confirm-result') window.answer = e.data; }); parent.postMessage({type:'axiom-confirm',id:'frame-confirm',message:'Frame delete'},location.origin); });
  await page.getByRole('dialog').filter({hasText:'Frame delete'}).waitFor();
  await page.keyboard.press('Escape');
  await frame.waitForFunction(() => !!window.answer);
  assert.deepEqual(await frame.evaluate(() => window.answer), {type:'axiom-confirm-result',id:'frame-confirm',confirmed:false});
  await page.frames().find(f => f.url().endsWith('/untrusted.html')).evaluate(() => parent.postMessage({type:'axiom-notify',kind:'error',message:'Rejected source'},location.origin));
  await page.evaluate(() => window.dispatchEvent(new MessageEvent('message',{origin:'https://attacker.invalid',source:document.querySelector('#trusted').contentWindow,data:{type:'axiom-notify',kind:'error',message:'Rejected origin'}})));
  await page.waitForTimeout(100);
  assert.equal(await page.getByText('Rejected source').count(),0);
  assert.equal(await page.getByText('Rejected origin').count(),0);
  assert.equal(await page.locator('body').innerText().then(text => text.includes('SuperGPT')),false);
  await page.reload();
  await page.waitForFunction(() => !!window.axiomNotify);
  await page.evaluate(() => window.axiomNotify({kind:'success',message:'Auto-hide first'}));
  const firstNotice = page.getByRole('status').filter({hasText:'Auto-hide first'});
  await firstNotice.waitFor();
  await page.waitForTimeout(3000);
  await page.evaluate(() => window.axiomNotify({kind:'error',message:'Auto-hide second'}));
  const secondNotice = page.getByRole('alert').filter({hasText:'Auto-hide second'});
  await secondNotice.waitFor();
  await firstNotice.waitFor({state:'hidden',timeout:3000});
  assert.equal(await secondNotice.count(),1, 'New delivery must not reset an older notice timer');
  await secondNotice.waitFor({state:'hidden',timeout:4000});
  await page.evaluate(() => window.axiomNotify({kind:'success',message:'Manual dismiss'}));
  const manualNotice = page.getByRole('status').filter({hasText:'Manual dismiss'});
  await manualNotice.getByRole('button',{name:'Tutup pemberitahuan'}).click();
  assert.equal(await manualNotice.count(),0);
  await page.evaluate(() => window.axiomNotify({kind:'success',message:'Manual dismiss'}));
  await manualNotice.waitFor();
  await manualNotice.waitFor({state:'hidden',timeout:7000});
  assert.equal(await page.locator('.d-sdk-toast').count(),0);
  console.log('PASS SDK notices, auto-hide independent deadlines, manual dismiss/redelivery, CSS isolation, focus trap/restore, Escape, confirmation queue, iframe origin/source checks');
} finally { await browser.close(); server.close(); }
