// JavaScript, billing-check.mjs, Node.js 24: isolated billing state and limit regression.
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
const dir=mkdtempSync(path.join(tmpdir(),'axiom-billing-'));
const original=process.env.NINEROUTER_DATA_DIR;
process.env.NINEROUTER_DATA_DIR=dir;mkdirSync(path.join(dir,'db'));
const setup=new DatabaseSync(path.join(dir,'db','data.sqlite'));
setup.exec('CREATE TABLE tokenPackages(id TEXT PRIMARY KEY,name TEXT NOT NULL,description TEXT,tokenAmount INTEGER NOT NULL,price INTEGER NOT NULL,rpmLimit INTEGER,tpmLimit INTEGER,validityDays INTEGER,allowedModels TEXT,blockedModels TEXT,features TEXT,badge TEXT,isActive INTEGER,isPopular INTEGER,sortOrder INTEGER,createdAt TEXT NOT NULL,updatedAt TEXT NOT NULL);CREATE TABLE apiKeys(id TEXT PRIMARY KEY,key TEXT NOT NULL,name TEXT,machineId TEXT,customerEmail TEXT,packageId TEXT,tokenLimit INTEGER,tokensUsed INTEGER,rpmLimit INTEGER,tpmLimit INTEGER,expiresAt TEXT,isActive INTEGER,allowedModels TEXT,blockedModels TEXT,createdAt TEXT NOT NULL)');
setup.exec('ALTER TABLE apiKeys ADD COLUMN providerConnectionId TEXT; CREATE TABLE providerConnections(id TEXT PRIMARY KEY,provider TEXT,name TEXT,isActive INTEGER,priority INTEGER)');
setup.close();
const {routerDb,packageSnapshot}=await import('./lib/merchant-commerce.mjs');
const {billingPackages,savePackage,deletePackage,billingKeys,updateBillingKey}=await import('./lib/merchant-billing.mjs');
const {default:modelPolicy}=await import('./lib/model-policy.cjs');
try {
  const input={name:'Smoke package',description:'isolated',tokenAmount:25000,price:12345,rpmLimit:12,tpmLimit:2400,validityDays:3,allowedModels:['cx/example'],features:['25k tokens'],badge:'',isActive:false,isPopular:false,sortOrder:0};
  const first=savePackage(input).package;assert.equal(first.price,12345);assert.equal(first.isActive,false);
  const second=savePackage({...input,price:23456,isActive:true},first.id).package;assert.equal(second.id,first.id);assert.equal(second.price,23456);
  assert.deepEqual(second.allowedModels,['cx/example']);assert.equal(second.blockedModels,null);
  const restricted=savePackage({...input,isActive:true,blockedModels:['example']},first.id).package;
  const snapshot=JSON.stringify(packageSnapshot(restricted));
  const {allowedModels:omittedAllow,...oldClient}=input;
  const preservedPackage=savePackage({...oldClient,isActive:true},first.id).package;
  assert.deepEqual(preservedPackage.allowedModels,['cx/example']);assert.deepEqual(preservedPackage.blockedModels,['example']);
  assert.equal(modelPolicy.policyAllowsModel(preservedPackage,'cx/example'),false);
  savePackage({...input,isActive:true,allowedModels:null,blockedModels:null},first.id);
  assert.deepEqual(JSON.parse(snapshot).allowedModels,['cx/example']);assert.deepEqual(JSON.parse(snapshot).blockedModels,['example']);
  const legacy=packageSnapshot({...input,isActive:true,id:'legacy',allowedModels:JSON.stringify(input.allowedModels)});
  assert.deepEqual(legacy.allowedModels,['cx/example']);assert.equal(legacy.blockedModels,null);
  assert.equal(modelPolicy.policyAllowsModel(legacy,'cx/example'),true);assert.equal(modelPolicy.policyAllowsModel(legacy,'cx/other'),false);
  assert.throws(()=>savePackage({...input,price:0}),{code:'invalid_billing'});
  assert.throws(()=>savePackage({...input,tokenAmount:1.5}),{code:'invalid_billing'});
  assert.throws(()=>savePackage({...input,allowedModels:['']}),{code:'invalid_billing'});
  assert.throws(()=>savePackage({...input,blockedModels:['Display Name']}),{code:'invalid_billing'});
  assert.equal(billingPackages().packages[0].tokenAmount,25000);
  const db=routerDb();
  const insert=db.prepare('INSERT INTO apiKeys(id,key,machineId,customerEmail,tokenLimit,tokensUsed,rpmLimit,tpmLimit,isActive,createdAt) VALUES(?,?,?,?,?,?,?,?,?,?)');
  insert.run('customer','secret-customer','axiom-qris','customer@example.invalid',25000,300,12,2400,1,new Date().toISOString());
  insert.run('internal','secret-internal','internal',null,0,0,0,0,1,new Date().toISOString());
  const manual=updateBillingKey('internal',{blockedModels:['model']}).key;
  assert.equal(manual.usable,true);assert.equal(modelPolicy.policyAllowsModel(manual,'cx/model'),false);
  assert.equal(modelPolicy.policyAllowsModel(manual,'cx/model-extra'),true);
  const updated=updateBillingKey('customer',{tokenLimit:50000,rpmLimit:8,expiresAt:'2030-01-01T00:00:00Z'}).key;
  assert.equal(updated.tokensUsed,300);assert.equal(updated.tokenLimit,50000);assert.equal(updated.rpmLimit,8);
  const scoped=updateBillingKey('customer',{allowedModels:['cx/*'],blockedModels:['example']}).key;
  assert.equal(modelPolicy.policyAllowsModel(scoped,'cx/example'),false);
  assert.equal(modelPolicy.policyAllowsModel(scoped,'cx/other'),true);
  const preserved=updateBillingKey('customer',{rpmLimit:9}).key;
  assert.deepEqual(preserved.allowedModels,['cx/*']);assert.deepEqual(preserved.blockedModels,['example']);
  assert.equal(preserved.tokensUsed,300);assert.equal(preserved.tokenLimit,50000);assert.equal(preserved.expiresAt,'2030-01-01T00:00:00.000Z');
  assert.equal(updateBillingKey('customer',{tokenLimit:300}).key.exhausted,true);
  assert.equal(updateBillingKey('customer',{tokenLimit:50000,expiresAt:'2000-01-01T00:00:00Z'}).key.usable,false);
  updateBillingKey('customer',{isActive:false});
  assert.equal(db.prepare('SELECT isActive FROM apiKeys WHERE id=?').get('customer').isActive,0);
  assert.equal(db.prepare('SELECT COUNT(*) n FROM apiKeys WHERE id=?').get('customer').n,1);
  assert.equal(billingKeys().keys.some(k=>'key' in k),false);
  deletePackage(first.id);assert.deepEqual(billingPackages().packages,[]);
  assert.throws(()=>deletePackage(first.id),{code:'not_found'});
  console.log('PASS: package policy round-trip, preserved snapshots, block precedence, manual-key management, quota preservation, unavailable status, revocation without deletion or secret exposure.');
} finally {
  routerDb().close();if(original===undefined)delete process.env.NINEROUTER_DATA_DIR;else process.env.NINEROUTER_DATA_DIR=original;
  rmSync(dir,{recursive:true,force:true});
}
