import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { initializeAnnouncements, saveAnnouncement, listAnnouncements } from './lib/announcements.mjs';
const db = new DatabaseSync(':memory:');
db.exec(`CREATE TABLE axiom_notices(notice_id TEXT PRIMARY KEY,enabled INTEGER,mode TEXT,target TEXT,target_group TEXT,event_type TEXT,priority INTEGER,start_at INTEGER,expires_at INTEGER,title TEXT,message TEXT)`);
initializeAnnouncements(db);
const now = Date.parse('2026-10-19T00:00:00Z');
const base = {title:'Release',slug:'release',category:'NEW',summary:'Release summary',content:'<script>alert(1)</script>',version:'1',status:'draft',published_at:new Date(now-1000).toISOString(),expires_at:null,audience:'public',is_pinned:false};
const draft = saveAnnouncement(db,base,now);
assert.deepEqual(listAnnouncements(db,'public',now),[]);
const published = saveAnnouncement(db,{...draft,status:'published',publish_to_api:true},now);
assert.equal(listAnnouncements(db,'public',now)[0].content,base.content);
assert.equal(db.prepare('SELECT mode FROM axiom_notices WHERE notice_id=?').get(draft.id).mode,'always');
assert.equal('publish_to_api' in listAnnouncements(db,'public',now)[0],false);
saveAnnouncement(db,{...published,audience:'customers',publish_to_api:false},now);
assert.equal(listAnnouncements(db,'public',now).length,0);
assert.equal(listAnnouncements(db,'customers',now)[0].id,draft.id);
assert.equal(db.prepare('SELECT mode FROM axiom_notices WHERE notice_id=?').get(draft.id).mode,'disabled');
saveAnnouncement(db,{...published,expires_at:new Date(now+1000).toISOString()},now);
assert.equal(listAnnouncements(db,'public',now+1000).length,0);
saveAnnouncement(db,{...published,published_at:new Date(now+1000).toISOString()},now);
assert.equal(listAnnouncements(db,'public',now).length,0);
assert.throws(()=>saveAnnouncement(db,{...base,slug:'other',summary:'api_key=secretvalue'},now));
assert.throws(()=>saveAnnouncement(db,{...base,slug:'release'},now));
assert.equal(listAnnouncements(db,'admin',now).length,1);
assert.throws(()=>saveAnnouncement(db,{...base,slug:'other',audience:'customers',publish_to_api:true},now));
assert.throws(()=>saveAnnouncement(db,{...base,published_at:'bad'},now));
assert.throws(()=>saveAnnouncement(db,{...base,slug:'other',is_pinned:'false'},now));
assert.throws(()=>saveAnnouncement(db,{...base,slug:'other',id:'missing'},now), /tidak ditemukan/);
for (const id of [null, '', 0, 123, [], {}]) assert.throws(() => saveAnnouncement(db, {...base, id}, now), /ID tidak valid/);
for (const summary of ['First line\nSecond line', 'First line\rSecond line', 'Pembaruan baru ✓']) assert.throws(() => saveAnnouncement(db, {...published, summary}, now), /ASCII satu baris/);
assert.throws(() => saveAnnouncement(db, {...base, published_at:null, expires_at:new Date(now+1000).toISOString()}, now), /Kedaluwarsa/);
assert.equal(db.prepare('SELECT COUNT(*) count FROM axiom_notices').get().count, 1);
const withdrawn = saveAnnouncement(db, {...published, status:'draft'}, now);
assert.equal(db.prepare('SELECT enabled FROM axiom_notices WHERE notice_id=?').get(withdrawn.id).enabled, 0);
assert.deepEqual(listAnnouncements(db, 'customers', now), []);
const {publish_to_api, ...withoutOptIn} = published;
saveAnnouncement(db, withoutOptIn, now);
assert.equal(db.prepare('SELECT mode FROM axiom_notices WHERE notice_id=?').get(draft.id).mode, 'disabled');
db.prepare("INSERT INTO axiom_notices(notice_id,enabled,mode,title,message) VALUES('legacy',1,'always','Legacy','Not public')").run();
assert.equal(listAnnouncements(db, 'public', now).length, 1);
const second = saveAnnouncement(db, {...base, slug:'second'}, now);
assert.throws(() => saveAnnouncement(db, {...second, slug:published.slug, title:'Must roll back'}, now));
assert.equal(db.prepare('SELECT title FROM axiom_notices WHERE notice_id=?').get(second.id).title, base.title);
db.close();
console.log('PASS announcement draft, audience isolation, scheduling, expiry, API opt-in, validation, atomic rollback');
